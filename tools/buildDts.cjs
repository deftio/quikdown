#!/usr/bin/env node
/**
 * buildDts.cjs — generate CommonJS type declarations (dist/*.d.cts) from the
 * hand-maintained ESM declarations (dist/*.d.ts).
 *
 * Why: package.json has "type": "module", so TypeScript reads every .d.ts as
 * ESM types (`export default X`). The CommonJS bundles do `module.exports = X`,
 * so a `require()` consumer under moduleResolution node16/nodenext needs
 * `export = X` types instead. Each .d.cts is derived mechanically:
 *
 *   export interface Foo {…}        →  interface Foo {…}  (+ re-exposed as X.Foo)
 *   import { A } from './quikdown.js' →  import __m0 = require('./quikdown.cjs'); type A = __m0.A;
 *   export default X;               →  export = X;
 *
 * quikdown_mcp is copied verbatim: its CJS bundle uses named exports plus
 * `exports.default`, which is exactly what `export default` means in a .d.cts.
 *
 * Usage: node tools/buildDts.cjs   (runs as part of `npm run build`)
 */
'use strict';

const fs = require('fs');
const path = require('path');

const DIST = path.join(__dirname, '..', 'dist');
const VERBATIM = new Set(['quikdown_mcp.d.ts']);
const HEADER = '// GENERATED by tools/buildDts.cjs from the matching .d.ts — do not edit.\n';

function toCts(src, file) {
    const defaultMatch = src.match(/^export default (\w+);\s*$/m);
    if (!defaultMatch) throw new Error(`${file}: no "export default <name>;" found`);
    const name = defaultMatch[1];

    const typeNames = [];
    let moduleIndex = 0;
    let out = src
        // relative ESM imports → CJS import-equals (+ local aliases for named types)
        .replace(/^import (\w+) from '(\.\/[\w-]+)\.js';\s*$/gm, (m, def, spec) => `import ${def} = require('${spec}.cjs');`)
        .replace(/^import \{([^}]+)\} from '(\.\/[\w-]+)\.js';\s*$/gm, (m, names, spec) => {
            const alias = `__m${moduleIndex++}`;
            const lines = [`import ${alias} = require('${spec}.cjs');`];
            for (const n of names.split(',').map(s => s.trim()).filter(Boolean)) {
                lines.push(`type ${n} = ${alias}.${n};`);
            }
            return lines.join('\n');
        })
        // top-level exported types become module-local …
        .replace(/^export (interface|type) (\w+)/gm, (m, kind, typeName) => {
            typeNames.push(typeName);
            return `${kind} ${typeName}`;
        })
        .replace(/^export default \w+;\s*$/m, '');

    if (/^import .* from /m.test(out) || /^export /m.test(out)) {
        throw new Error(`${file}: unsupported top-level import/export (extend tools/buildDts.cjs)`);
    }

    // … and are re-exposed on the exported value's namespace (X.Foo).
    if (typeNames.length) {
        out += typeNames.map(n => `type __${n} = ${n};`).join('\n') + '\n';
        out += `declare namespace ${name} {\n`;
        out += typeNames.map(n => `    export type ${n} = __${n};`).join('\n') + '\n}\n';
    }
    out += `\nexport = ${name};\n`;
    return out;
}

let count = 0;
for (const file of fs.readdirSync(DIST).filter(f => f.endsWith('.d.ts')).sort()) {
    const src = fs.readFileSync(path.join(DIST, file), 'utf8');
    const body = VERBATIM.has(file) ? src : toCts(src, file);
    fs.writeFileSync(path.join(DIST, file.replace(/\.d\.ts$/, '.d.cts')), HEADER + body);
    count++;
}
console.log(`buildDts: wrote ${count} .d.cts files`);
